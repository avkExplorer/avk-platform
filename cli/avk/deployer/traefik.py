"""Traefik routes for apps: one dynamic-config file per app, written atomically so traffic moves in one step."""

from __future__ import annotations

import os
from pathlib import Path

from avk import config


def routes_dir() -> Path:
    return config.avk_home() / "state" / "traefik"


def route_yaml(app: str, hosts: list[str], backend_url: str) -> str:
    rule = " || ".join(f"Host(`{h}`)" for h in hosts)
    return "\n".join([
        f"# generated by the AVK deployer for {app}; do not edit",
        "http:",
        "  routers:",
        f"    {app}:",
        f"      rule: {rule}",
        "      entryPoints: [web]",
        f"      service: {app}",
        "  services:",
        f"    {app}:",
        "      loadBalancer:",
        "        servers:",
        f"          - url: {backend_url}",
        "",
    ])


class Routes:
    def __init__(self, root: Path | None = None):
        self.root = root or routes_dir()

    def path(self, app: str) -> Path:
        return self.root / f"{app}.yml"

    def snapshot(self, app: str) -> str | None:
        p = self.path(app)
        return p.read_text(encoding="utf-8") if p.is_file() else None

    def write(self, app: str, text: str) -> None:
        """Temp file in the same folder (ignored by Traefik: not .yml), then an atomic rename."""
        self.root.mkdir(parents=True, exist_ok=True)
        tmp = self.root / f".{app}.yml.tmp"
        tmp.write_text(text, encoding="utf-8", newline="\n")
        os.replace(tmp, self.path(app))

    def point(self, app: str, hosts: list[str], backend_url: str) -> None:
        self.write(app, route_yaml(app, hosts, backend_url))

    def restore(self, app: str, snapshot: str | None) -> None:
        if snapshot is None:
            self.path(app).unlink(missing_ok=True)
        else:
            self.write(app, snapshot)
